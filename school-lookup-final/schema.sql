CREATE TABLE IF NOT EXISTS students (
  id TEXT,
  name TEXT,
  grade TEXT,
  class TEXT,
  phone TEXT
);

-- Per (grade, class) toggle controlling whether students in that class can
-- be looked up on the public site. Missing rows default to enabled.
CREATE TABLE IF NOT EXISTS class_visibility (
  grade TEXT NOT NULL,
  class TEXT NOT NULL,
  enabled INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (grade, class)
);

-- Noor system grade-code -> grade-name mapping, editable from the
-- admin panel so new stages/codes don't require a code change.
CREATE TABLE IF NOT EXISTS grade_mappings (
  code TEXT PRIMARY KEY,
  grade_name TEXT NOT NULL,
  created_at INTEGER NOT NULL
);
