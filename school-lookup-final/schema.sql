-- Admin panel session tokens, created on login and checked on every
-- /api/admin/* request.
CREATE TABLE IF NOT EXISTS admin_sessions (
  token TEXT PRIMARY KEY,
  expires_at INTEGER NOT NULL
);

-- Admin panel settings, notably the hashed (SHA-256) login password
-- (key = 'password_hash'). Kept in D1 rather than a Cloudflare Pages
-- secret so it can be changed instantly from the dashboard itself,
-- without needing a new deployment for the change to take effect.
CREATE TABLE IF NOT EXISTS admin_config (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- Fixed-window rate limiting (used for admin login attempts).
CREATE TABLE IF NOT EXISTS rate_limits (
  key TEXT PRIMARY KEY,
  count INTEGER NOT NULL DEFAULT 0,
  window_start INTEGER NOT NULL DEFAULT 0
);

-- Admin action audit trail (logins, imports, edits, deletes, toggles).
CREATE TABLE IF NOT EXISTS activity_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  type TEXT NOT NULL,
  detail TEXT,
  ip TEXT,
  created_at INTEGER NOT NULL
);

-- Every public lookup attempt on the student page, for the admin
-- search-analytics dashboard. ip_hash is a SHA-256 of the visitor's
-- IP (never the raw address) so counts can be de-duplicated without
-- storing anything identifying.
CREATE TABLE IF NOT EXISTS search_logs (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  national_id_searched TEXT NOT NULL,
  found INTEGER NOT NULL DEFAULT 0,
  searched_at INTEGER NOT NULL,
  ip_hash TEXT,
  user_agent TEXT
);
CREATE INDEX IF NOT EXISTS idx_search_logs_searched_at ON search_logs (searched_at);

